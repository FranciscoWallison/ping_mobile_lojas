# ---------------------------------------------------------------------------
# Resultado
# ---------------------------------------------------------------------------
@dataclass
class Detection:
    vendor: str
    layer: str
    evidence: list[str] = field(default_factory=list)

    @property
    def label(self) -> str:
        return f"{self.vendor} ({LAYER_LABELS.get(self.layer, self.layer)})"


@dataclass
class BlockInfo:
    source: str          # quem bloqueou (ex.: "Cloudflare", "F5 BIG-IP ASM / Advanced WAF")
    category: str        # desafio / bloqueio / rate_limit / origem / indefinido
    kind: str            # descrição curta do tipo de bloqueio
    reference: str = ""  # ID para o time de infra achar o evento no log
    hint: str = ""       # próximo passo recomendado

    def short(self) -> str:
        ref = f" [{self.reference}]" if self.reference else ""
        return f"{self.source}: {self.kind}{ref}"


# ---------------------------------------------------------------------------
# Normalização
# ---------------------------------------------------------------------------
def normalize_headers(headers) -> dict[str, list[str]]:
    """
    Aceita dict (str ou lista como valor — formato GlobalPing), lista de tuplas
    ou objetos tipo HTTPHeaderDict e devolve {nome_minúsculo: [valores]}.
    """
    out: dict[str, list[str]] = {}
    if not headers:
        return out
    items = headers.items() if hasattr(headers, "items") else headers
    for k, v in items:
        values = v if isinstance(v, (list, tuple)) else [v]
        out.setdefault(str(k).lower(), []).extend(str(x) for x in values if x is not None)
    return out


def cookie_names(headers: dict[str, list[str]]) -> dict[str, str]:
    """Extrai {nome: valor} de todos os Set-Cookie."""
    out: dict[str, str] = {}
    for raw in headers.get("set-cookie", []):
        # Alguns clientes juntam vários Set-Cookie com vírgula; quebra só antes de "nome=".
        for part in re.split(r",\s*(?=[^;,=\s]+=)", raw):
            first = part.split(";", 1)[0].strip()
            if "=" in first:
                name, value = first.split("=", 1)
                out.setdefault(name.strip(), value.strip())
    return out


# ---------------------------------------------------------------------------
# Fingerprint
# ---------------------------------------------------------------------------
def _merge(found: dict[str, Detection], sig: Signature, evidence: str) -> None:
    det = found.setdefault(sig.vendor, Detection(sig.vendor, sig.layer))
    if evidence not in det.evidence:
        det.evidence.append(evidence)


def fingerprint_response(headers, body: str = "") -> list[Detection]:
    """Detecta fornecedores a partir de headers, cookies e corpo de uma resposta HTTP."""
    h = normalize_headers(headers)
    cookies = cookie_names(h)
    body = html.unescape(body or "")
    found: dict[str, Detection] = {}

    for sig in SIGNATURES:
        for name, pattern in sig.headers:
            for value in h.get(name, []):
                if pattern is None or re.search(pattern, value, re.I):
                    _merge(found, sig, f"header {name}: {value[:80]}")
                    break
        for pattern in sig.cookies:
            for cname, cvalue in cookies.items():
                if re.search(pattern, cname):
                    ev = f"cookie {cname}"
                    if cname.startswith("BIGipServer"):
                        ev += f" ({describe_bigip_cookie(cname, cvalue)})"
                    _merge(found, sig, ev)
        for pattern in sig.body:
            m = re.search(pattern, body, re.I)
            if m:
                _merge(found, sig, f"corpo contém '{m.group(0)[:60]}'")

    return sort_stack(found.values())


def fingerprint_cname(cnames: list[str]) -> list[Detection]:
    found: dict[str, Detection] = {}
    for cname in cnames:
        for sig in SIGNATURES:
            if any(re.search(p, cname, re.I) for p in sig.cnames):
                _merge(found, sig, f"CNAME {cname}")
    return sort_stack(found.values())


def fingerprint_asn(asn: int | None, as_name: str = "") -> list[Detection]:
    if not asn:
        return []
    found: dict[str, Detection] = {}
    for sig in SIGNATURES:
        if asn in sig.asns:
            _merge(found, sig, f"IP no ASN {asn} {as_name}".strip())
    return sort_stack(found.values())


def describe_asn(asn: int | None, as_name: str = "") -> str:
    """Explica o que o ASN do IP de destino diz sobre a hospedagem."""
    if not asn:
        return "ASN desconhecido"
    provider = ASN_PROVIDERS.get(asn)
    if provider:
        return f"AS{asn} = {provider} (nuvem/CDN: a borda é do provedor)"
    return (f"AS{asn} {as_name} — operadora/rede própria: o IP não é de CDN, então o site "
            "provavelmente está em datacenter próprio ou colocation, com appliances "
            "on-premise (F5, FortiWeb, NetScaler...) na frente da aplicação")


def sort_stack(detections) -> list[Detection]:
    return sorted(detections, key=lambda d: (LAYER_ORDER.get(d.layer, 9), d.vendor))


def merge_detections(*groups: list[Detection]) -> list[Detection]:
    found: dict[str, Detection] = {}
    for group in groups:
        for d in group:
            cur = found.setdefault(d.vendor, Detection(d.vendor, d.layer))
            for ev in d.evidence:
                if ev not in cur.evidence:
                    cur.evidence.append(ev)
    return sort_stack(found.values())


def stack_labels(detections: list[Detection]) -> list[str]:
    return [d.label for d in detections]


# ---------------------------------------------------------------------------
# F5: cookie de persistência BIGipServer<pool>
# ---------------------------------------------------------------------------
def decode_bigip_cookie(value: str) -> str | None:
    """
    Decodifica o cookie de persistência do F5 LTM quando ele NÃO está criptografado.
    Formato IPv4 padrão: "<ip little-endian>.<porta byte-swapped>.0000".
    Retorna "ip:porta" do membro do pool interno, ou None.
    """
    m = re.fullmatch(r"(\d+)\.(\d+)\.0000", value)
    if m:
        ip = socket.inet_ntoa(struct.pack("<I", int(m.group(1))))
        port = struct.unpack("<H", struct.pack(">H", int(m.group(2))))[0]
        return f"{ip}:{port}"
    m = re.fullmatch(r"rd\d+o0{20}ffff([0-9a-f]{8})o(\d+)", value)  # com route domain
    if m:
        ip = socket.inet_ntoa(bytes.fromhex(m.group(1)))
        return f"{ip}:{m.group(2)}"
    return None


def describe_bigip_cookie(name: str, value: str) -> str:
    pool = name[len("BIGipServer"):] or "?"
    if value.startswith("!"):
        return f"pool '{pool}', valor criptografado"
    member = decode_bigip_cookie(value)
    if member:
        return f"pool '{pool}', membro interno {member} — vazamento de IP interno"
    return f"pool '{pool}'"


