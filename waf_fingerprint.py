CLOUDFLARE_ERRORS = {
    "1006": "IP banido pelo dono do site",
    "1007": "IP banido pelo dono do site",
    "1008": "IP banido pelo dono do site",
    "1009": "país/região bloqueado pelo dono do site",
    "1010": "assinatura do navegador/cliente banida",
    "1012": "acesso negado por regra de segurança",
    "1015": "rate limit (muitas requisições)",
    "1020": "bloqueado por regra de firewall (custom rule)",
}

_HINT_CF_CHALLENGE = (
    "A borda Cloudflare exigiu um desafio JavaScript e a requisição não chegou à origem. "
    "Clientes sem navegador (curl, Insomnia, app mobile, integrações) nunca passam. "
    "Peça ao time do Cloudflare uma regra WAF 'Skip' para o caminho da API "
    "(ou allowlist do IP/ASN de saída, ou token/mTLS) e informe o CF-RAY."
)


def _first(h: dict[str, list[str]], name: str) -> str:
    vals = h.get(name) or [""]
    return vals[0]


def _ref(label: str, value: str) -> str:
    return f"{label} {value}" if value else ""


def classify_block(status: int | None, headers, body: str = "") -> BlockInfo | None:
    """Identifica quem respondeu o bloqueio e o ID para rastrear no log."""
    if status is None or status < 400:
        return None
    h = normalize_headers(headers)
    body = html.unescape(body or "")
    cf_ray = _first(h, "cf-ray")

    # Cloudflare
    if _first(h, "cf-mitigated").lower() == "challenge":
        return BlockInfo("Cloudflare", "desafio", "Managed Challenge (desafio JS)",
                         _ref("CF-RAY", cf_ray), _HINT_CF_CHALLENGE)
    m = re.search(r"(?:error code:?\s*|cf-error-code[^>]*>\s*)(10\d\d)", body, re.I)
    if m:
        code = m.group(1)
        cat = "rate_limit" if code == "1015" else "bloqueio"
        return BlockInfo("Cloudflare", cat, f"erro {code} — {CLOUDFLARE_ERRORS.get(code, 'bloqueio')}",
                         _ref("CF-RAY", cf_ray),
                         "Regra configurada no painel Cloudflare (Security > Events). "
                         "Informe o CF-RAY ao time responsável.")
    if re.search(r"Sorry, you have been blocked", body, re.I):
        return BlockInfo("Cloudflare", "bloqueio", "bloqueado por regra WAF",
                         _ref("CF-RAY", cf_ray),
                         "Bloqueio explícito (não é desafio). Informe o CF-RAY ao time do Cloudflare.")
    if re.search(r"_cf_chl_opt|/cdn-cgi/challenge-platform|<title>Just a moment", body, re.I):
        return BlockInfo("Cloudflare", "desafio", "desafio JS/Turnstile",
                         _ref("CF-RAY", cf_ray), _HINT_CF_CHALLENGE)

    # F5 BIG-IP ASM / Advanced WAF (e NGINX App Protect, que usa a mesma página)
    if re.search(r"The requested URL was rejected", body, re.I):
        m = re.search(r"support ID is:?\s*(?:<[^>]+>\s*)*([0-9]+)", body, re.I)
        return BlockInfo("F5 BIG-IP ASM / Advanced WAF", "bloqueio", "violação de política ASM",
                         f"Support ID {m.group(1)}" if m else "",
                         "Envie o Support ID ao time de segurança: ele localiza a violação "
                         "exata em Security > Event Logs > Application > Requests.")

    # Akamai
    if re.search(r"Access Denied", body) and re.search(r"Reference\s*#", body):
        m = re.search(r"Reference\s*#\s*([0-9a-f.]+)", body, re.I)
        return BlockInfo("Akamai", "bloqueio", "negado pelo App & API Protector / Kona",
                         f"Reference #{m.group(1)}" if m else "",
                         "Envie o Reference # ao time que administra a Akamai.")

    # Imperva
    m = re.search(r"Incapsula incident ID:?\s*([0-9-]+)", body, re.I)
    if m or ("x-iinfo" in h and status == 403):
        return BlockInfo("Imperva (Incapsula)", "bloqueio", "negado pela política Imperva",
                         f"Incident ID {m.group(1)}" if m else "",
                         "Envie o Incident ID ao time que administra o Imperva.")

    # AWS
    if "x-amzn-waf-action" in h:
        action = _first(h, "x-amzn-waf-action")
        return BlockInfo("AWS WAF", "desafio" if action in ("challenge", "captcha") else "bloqueio",
                         f"ação {action}", _ref("x-amz-cf-id", _first(h, "x-amz-cf-id")),
                         "Regra do Web ACL (AWS WAF). Informe o x-amz-cf-id / horário.")
    if re.search(r"Request blocked\.", body) and re.search(r"cloudfront", body, re.I):
        return BlockInfo("AWS CloudFront / AWS WAF", "bloqueio", "Request blocked",
                         _ref("x-amz-cf-id", _first(h, "x-amz-cf-id")),
                         "Bloqueio no CloudFront (geo restriction ou Web ACL).")

    # Azure
    if "x-azure-ref" in h and status == 403:
        return BlockInfo("Azure Front Door WAF", "bloqueio", "negado pela política WAF do Front Door",
                         _ref("x-azure-ref", _first(h, "x-azure-ref")),
                         "Informe o x-azure-ref ao time de Azure (logs FrontDoorWebApplicationFirewallLog).")
    if re.search(r"^Microsoft-Azure-Application-Gateway", _first(h, "server")) and status == 403:
        return BlockInfo("Azure Application Gateway WAF", "bloqueio", "negado pelo WAF do App Gateway",
                         "", "Ver ApplicationGatewayFirewallLog no Log Analytics.")

    # Appliances
    m = re.search(r"Attack ID:?\s*(\d+)", body)
    if m or re.search(r"FortiWeb|Web Page Blocked!", body):
        return BlockInfo("Fortinet FortiWeb / FortiGate", "bloqueio", "negado pela política Fortinet",
                         f"Attack ID {m.group(1)}" if m else "",
                         "Envie o Attack ID / Event ID ao time de segurança.")
    if re.search(r"Unauthorized Activity Has Been Detected", body, re.I):
        m = re.search(r"Case Number:?\s*(\S+)", body, re.I)
        return BlockInfo("Radware", "bloqueio", "negado pela política Radware",
                         f"Case {m.group(1)}" if m else "", "Envie o Case Number ao time de segurança.")
    if re.search(r"Mod_Security|ModSecurity", body, re.I):
        return BlockInfo("ModSecurity", "bloqueio", "regra ModSecurity (OWASP CRS)", "",
                         "Ver audit log do ModSecurity no servidor.")

    # Origem IIS
    if re.search(r"403 - (Forbidden: Access is denied|Proibido: o acesso foi negado)", body, re.I) \
            or re.search(r"HTTP Error 403\.\d+", body):
        sub = re.search(r"HTTP Error (403\.\d+)", body)
        return BlockInfo("IIS (origem)", "origem",
                         f"negado pelo próprio servidor IIS{' (' + sub.group(1) + ')' if sub else ''}",
                         "",
                         "O bloqueio é na origem, não no WAF de borda: verifique IP and Domain "
                         "Restrictions, autenticação/autorização e permissões no IIS.")

    if status == 429:
        return BlockInfo("indefinido", "rate_limit", "HTTP 429 — limite de requisições", _ref("CF-RAY", cf_ray),
                         "Reduza a taxa ou peça aumento do limite.")
    if status in (401, 403, 406, 451):
        return BlockInfo("indefinido", "indefinido",
                         f"HTTP {status} sem página de bloqueio reconhecível", "",
                         "Compare os headers com a pilha detectada: pode ser regra da origem "
                         "(autenticação/aplicação) ou um WAF que esconde a assinatura.")
    return None
